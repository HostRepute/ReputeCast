package webhooks_test

import (
	"bytes"
	"encoding/json"
	"net/http"
	"os"
	"strconv"
	"testing"
	"time"

	"github.com/hostrepute/reputecast/internal/webhooks"
)

// vectorsFile holds the deliveries the client SDKs' webhook verifiers
// (sdk/client-ts, sdk/client-python, sdk/client-go) are tested with,
// signed here with Sign and checked here with Verify, so the SDKs accept
// exactly what the server sends. REPUTECAST_UPDATE_VECTORS=1 rewrites it.
const vectorsFile = "../../sdk/testdata/webhook-vectors.json"

// vectorTolerance is how far a delivery's timestamp may be from the
// receiver's clock: the SDKs' default, as docs/api/README.md recommends.
const vectorTolerance = 5 * time.Minute

type webhookVector struct {
	Name string `json:"name"`
	// Secrets are the receiver's: a delivery is valid when one of them
	// signed it.
	Secrets []string          `json:"secrets"`
	Body    string            `json:"body"`
	Headers map[string]string `json:"headers"`
	// Now is the receiver's clock, in Unix seconds.
	Now   int64 `json:"now"`
	Valid bool  `json:"valid"`
	// Error is why an invalid delivery is refused: "missing_header",
	// "timestamp" (outside the tolerance) or "signature".
	Error string `json:"error,omitempty"`
}

type webhookVectors struct {
	About            string          `json:"about"`
	ToleranceSeconds int             `json:"toleranceSeconds"`
	Vectors          []webhookVector `json:"vectors"`
}

func buildWebhookVectors() webhookVectors {
	const (
		current  = "whsec_test-vectors-current-secret"
		previous = "whsec_test-vectors-previous-secret"
		other    = "whsec_test-vectors-another-endpoint"
		ts       = int64(1767225600) // 2026-01-01T00:00:00Z
	)
	body := `{"id":"0193a6f0-0000-7000-8000-000000000001","type":"contact.subscribed","created_at":"2026-01-01T00:00:00Z",` +
		`"workspace":"acme-newsletter","data":{"email":"ana.nunez@example.com","name":"Ana Núñez","lists":["Weekly Digest"]}}`
	tsHeader := strconv.FormatInt(ts, 10)
	sigCurrent := webhooks.Sign(current, ts, []byte(body))
	sigPrevious := webhooks.Sign(previous, ts, []byte(body))
	signed := func(sig string) map[string]string {
		return map[string]string{webhooks.HeaderTimestamp: tsHeader, webhooks.HeaderSignature: sig}
	}
	upper := []byte(sigCurrent)
	for i, c := range upper {
		if c >= 'a' && c <= 'f' {
			upper[i] = c - 'a' + 'A'
		}
	}
	return webhookVectors{
		About: "Webhook deliveries signed by the ReputeCast server (internal/webhooks.Sign) for the client SDKs' tests. " +
			"Generated by TestWebhookVectors; regenerate with REPUTECAST_UPDATE_VECTORS=1 go test -run TestWebhookVectors ./internal/webhooks/.",
		ToleranceSeconds: int(vectorTolerance / time.Second),
		Vectors: []webhookVector{
			{Name: "one signature", Secrets: []string{current}, Body: body, Headers: signed(sigCurrent), Now: ts + 5, Valid: true},
			{Name: "two signatures after a rotation, checked with the new secret", Secrets: []string{current}, Body: body,
				Headers: signed(sigCurrent + "," + sigPrevious), Now: ts + 5, Valid: true},
			{Name: "two signatures after a rotation, checked with the previous secret", Secrets: []string{previous}, Body: body,
				Headers: signed(sigCurrent + "," + sigPrevious), Now: ts + 5, Valid: true},
			{Name: "two signatures with a space after the comma", Secrets: []string{previous}, Body: body,
				Headers: signed(sigCurrent + ", " + sigPrevious), Now: ts + 5, Valid: true},
			{Name: "one of the receiver's secrets", Secrets: []string{other, current}, Body: body, Headers: signed(sigCurrent), Now: ts + 5, Valid: true},
			{Name: "header names in lower case", Secrets: []string{current}, Body: body,
				Headers: map[string]string{"x-reputecast-timestamp": tsHeader, "x-reputecast-signature": sigCurrent}, Now: ts + 5, Valid: true},
			{Name: "at the edge of the tolerance", Secrets: []string{current}, Body: body, Headers: signed(sigCurrent), Now: ts + 300, Valid: true},
			{Name: "wrong secret", Secrets: []string{other}, Body: body, Headers: signed(sigCurrent), Now: ts + 5, Error: "signature"},
			{Name: "tampered body", Secrets: []string{current}, Body: body[:len(body)-2] + `,"Monthly Roundup"]}}`, Headers: signed(sigCurrent), Now: ts + 5, Error: "signature"},
			{Name: "signature for another timestamp", Secrets: []string{current}, Body: body,
				Headers: map[string]string{webhooks.HeaderTimestamp: strconv.FormatInt(ts+60, 10), webhooks.HeaderSignature: sigCurrent}, Now: ts + 60, Error: "signature"},
			{Name: "signature in upper-case hex", Secrets: []string{current}, Body: body, Headers: signed(string(upper)), Now: ts + 5, Error: "signature"},
			{Name: "expired timestamp", Secrets: []string{current}, Body: body, Headers: signed(sigCurrent), Now: ts + 301, Error: "timestamp"},
			{Name: "timestamp too far in the future", Secrets: []string{current}, Body: body, Headers: signed(sigCurrent), Now: ts - 301, Error: "timestamp"},
			{Name: "no signature header", Secrets: []string{current}, Body: body,
				Headers: map[string]string{webhooks.HeaderTimestamp: tsHeader}, Now: ts + 5, Error: "missing_header"},
			{Name: "no timestamp header", Secrets: []string{current}, Body: body,
				Headers: map[string]string{webhooks.HeaderSignature: sigCurrent}, Now: ts + 5, Error: "missing_header"},
		},
	}
}

// The SDKs' test deliveries are what the server signs, and the server's own
// check agrees with each verdict.
func TestWebhookVectors(t *testing.T) {
	v := buildWebhookVectors()
	for _, c := range v.Vectors {
		h := http.Header{}
		for k, val := range c.Headers {
			h.Set(k, val)
		}
		valid := false
		if ts, err := strconv.ParseInt(h.Get(webhooks.HeaderTimestamp), 10, 64); err == nil {
			for _, s := range c.Secrets {
				valid = valid || webhooks.Verify(s, h.Get(webhooks.HeaderSignature), ts, []byte(c.Body), time.Unix(c.Now, 0), vectorTolerance)
			}
		}
		if valid != c.Valid || valid != (c.Error == "") {
			t.Errorf("%s: the server's Verify says %v, the vector %v (%q)", c.Name, valid, c.Valid, c.Error)
		}
	}

	b, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	b = append(b, '\n')
	if os.Getenv("REPUTECAST_UPDATE_VECTORS") == "1" {
		if err := os.WriteFile(vectorsFile, b, 0o644); err != nil { //nolint:gosec // a committed test fixture
			t.Fatal(err)
		}
		return
	}
	have, err := os.ReadFile(vectorsFile)
	if err != nil {
		t.Fatalf("%v: run REPUTECAST_UPDATE_VECTORS=1 go test -run TestWebhookVectors ./internal/webhooks/", err)
	}
	if !bytes.Equal(have, b) {
		t.Fatalf("%s is out of date: run REPUTECAST_UPDATE_VECTORS=1 go test -run TestWebhookVectors ./internal/webhooks/", vectorsFile)
	}
}
