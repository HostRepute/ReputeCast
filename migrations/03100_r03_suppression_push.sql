-- +goose Up
-- PR-1 Suppression push. The shared list gets an insert sequence, and each
-- provider's suppression list is tracked entry by entry: what ReputeCast
-- pushed there and what it pulled from there. A sync pushes the qualifying
-- suppressions the provider doesn't hold yet (in insert order, so a late
-- bounce or an imported history is never skipped because of its date),
-- removes there what left the shared list, and the pending count is both.

ALTER TABLE suppressions ADD COLUMN seq bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY;
CREATE INDEX suppressions_seq_idx ON suppressions (workspace_id, seq);

CREATE TABLE provider_suppression_entries (
    provider_id uuid        NOT NULL REFERENCES providers(id) ON DELETE CASCADE,
    email       text        NOT NULL CHECK (email = lower(email)),
    -- pushed: ReputeCast added it from the shared list; pulled: the
    -- provider suppressed it and ReputeCast copied it into the shared list.
    origin      text        NOT NULL CHECK (origin IN ('pushed','pulled')),
    -- The shared list's insert sequence of the suppression that was pushed.
    seq         bigint      NOT NULL DEFAULT 0,
    synced_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (provider_id, email)
);

-- Where a provider's suppression list lives, as the last sync used it:
-- account (the provider account's own list), tenant (Amazon SES tenant of
-- the workspace), stream (Postmark message streams), domain, local (no
-- suppression API: enforced by ReputeCast before sending).
ALTER TABLE provider_suppression_sync ADD COLUMN scope   text   NOT NULL DEFAULT '';
-- The highest insert sequence pushed (for the sync status).
ALTER TABLE provider_suppression_sync ADD COLUMN push_seq bigint NOT NULL DEFAULT 0;
-- Addresses removed at the provider because they left the shared list.
ALTER TABLE provider_suppression_sync ADD COLUMN removed bigint NOT NULL DEFAULT 0;

-- +goose Down
