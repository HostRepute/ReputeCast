/**
 * Generates src/styles/tokens.css from the design system's tokens.json
 * (design/design-system/tokens.json), so the app always uses the exact
 * values of the Clearwater design system. Run with `pnpm tokens`.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

type Token = { name: string; value: string | Record<string, string>; usage?: string }
type Family = { tokens: Token[] }
type Tokens = {
  color: Family
  spacing: Family
  radius: Family
  shadow: Family
  duration: Family
  easing: Family
  type: { families: Record<string, string> }
}

const src = fileURLToPath(new URL('../../design/design-system/tokens.json', import.meta.url))
const out = fileURLToPath(new URL('../src/styles/tokens.css', import.meta.url))
const t = JSON.parse(readFileSync(src, 'utf8')) as Tokens

const value = (v: Token['value']) => (typeof v === 'string' ? v : (v.light ?? Object.values(v)[0] ?? ''))
const ref = (v: string) => v.replace(/^\{([\w.-]+)\}$/, 'var(--$1)')

const lines: string[] = [
  '/* Generated by scripts/tokens.ts from design/design-system/tokens.json. Do not edit. */',
  ':root {',
]
for (const tok of t.color.tokens) lines.push(`  --${tok.name}: ${ref(value(tok.value))};`)
for (const fam of [t.spacing, t.radius, t.shadow, t.duration, t.easing]) {
  for (const tok of fam.tokens) lines.push(`  --${tok.name.replace('.', '_')}: ${ref(value(tok.value))};`)
}
for (const [k, v] of Object.entries(t.type.families)) lines.push(`  --font-family-${k}: ${v};`)
lines.push('}', '')
writeFileSync(out, lines.join('\n'))
console.log(`wrote ${out}`)
