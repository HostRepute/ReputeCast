/**
 * Generates the app's token stylesheets from the design system's tokens.json
 * (design/design-system/tokens.json), so the app always uses the exact
 * values of the Clearwater design system. Run with `pnpm tokens`.
 *
 *   src/styles/tokens.css  the light values on :root. The landing site
 *                          (site/) imports it too, and is light only.
 *   src/styles/themes.css  the app's dark theme and the .keep-light scope:
 *                          - html[data-theme='dark'] (lib/theme sets it from
 *                            the member's choice or the device);
 *                          - the device's dark preference before the app's
 *                            scripts have run (no data-theme yet);
 *                          - .keep-light, which puts the light values back
 *                            for a preview of something readers see in
 *                            light (an email, a public page, a phone);
 *                          - .keep-dark, the same for a picture of the dark
 *                            theme (Appearance);
 *                          - print, which is always light (paper is white).
 *
 * A token's value is a string (the same in both themes) or an object with
 * `light` and `dark`.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

type Value = string | { light: string; dark?: string }
export type Token = { name: string; value: Value; usage?: string }
type Family = { tokens: Token[] }
export type Tokens = {
  color: Family
  spacing: Family
  radius: Family
  shadow: Family
  duration: Family
  easing: Family
  type: { families: Record<string, string> }
}

// This folder: from the module's URL when run by Node, from web/ under Vitest's jsdom.
const here = import.meta.url.startsWith('file:') ? dirname(fileURLToPath(import.meta.url)) : resolve('scripts')
export const tokensJSON = resolve(here, '../../design/design-system/tokens.json')
export const tokensCSS = resolve(here, '../src/styles/tokens.css')
export const themesCSS = resolve(here, '../src/styles/themes.css')

const light = (v: Value) => (typeof v === 'string' ? v : v.light)
const dark = (v: Value) => (typeof v === 'string' ? v : (v.dark ?? v.light))
const ref = (v: string) => v.replace(/^\{([\w.-]+)\}$/, 'var(--$1)')
const prop = (name: string) => `--${name.replace('.', '_')}`

/** Every colour token's value in a theme, references ({ink}) resolved. */
export function palette(t: Tokens, theme: 'light' | 'dark'): Record<string, string> {
  const out: Record<string, string> = {}
  for (const tok of t.color.tokens) out[tok.name] = theme === 'dark' ? dark(tok.value) : light(tok.value)
  for (const k of Object.keys(out)) for (let i = 0; i < 5 && /^\{.+\}$/.test(out[k]!); i++) out[k] = out[out[k]!.slice(1, -1)]!
  return out
}

/** The two stylesheets, as text. */
export function build(t: Tokens): { tokens: string; themes: string } {
  // tokens.css: every token's light value.
  const lines: string[] = ['/* Generated by scripts/tokens.ts from design/design-system/tokens.json. Do not edit. */', ':root {']
  for (const fam of [t.color, t.spacing, t.radius, t.shadow, t.duration, t.easing]) for (const tok of fam.tokens) lines.push(`  ${prop(tok.name)}: ${ref(light(tok.value))};`)
  for (const [k, v] of Object.entries(t.type.families)) lines.push(`  --font-family-${k}: ${v};`)
  lines.push('}', '')

  // themes.css: the tokens whose value differs by theme.
  const all = [...t.color.tokens, ...t.shadow.tokens]
  const varying = all.filter((tok) => typeof tok.value !== 'string' && tok.value.dark !== undefined && tok.value.dark !== tok.value.light)
  const block = (pick: (v: Value) => string, indent: string) => varying.map((tok) => `${indent}${prop(tok.name)}: ${ref(pick(tok.value))};`)
  // A token that only names another (focus → accent) is resolved where it is
  // declared, on :root, and inherited as a colour: a scope declares it again
  // so it follows the scope's values.
  const refs = all.filter((tok) => typeof tok.value === 'string' && /^\{[\w.-]+\}$/.test(tok.value))
  const refBlock = (indent: string) => refs.map((tok) => `${indent}${prop(tok.name)}: ${ref(tok.value as string)};`)

  const themes: string[] = [
    '/* Generated by scripts/tokens.ts from design/design-system/tokens.json. Do not edit. */',
    '/* The app is light unless the member chose Dark, or chose "Same as device" on a dark device. */',
    ':root {',
    '  color-scheme: light;',
    '}',
    ":root[data-theme='dark'] {",
    '  color-scheme: dark;',
    ...block(dark, '  '),
    ...refBlock('  '),
    '}',
    '/* Before lib/theme has run (it sets data-theme), the device decides. */',
    '@media (prefers-color-scheme: dark) {',
    '  :root:not([data-theme]) {',
    '    color-scheme: dark;',
    ...block(dark, '    '),
    ...refBlock('    '),
    '  }',
    '}',
    '/* A preview of what readers see in light (an email, a public page, a phone screen): the light values whatever the theme. */',
    '.keep-light {',
    '  color-scheme: light;',
    ...block(light, '  '),
    ...refBlock('  '),
    '}',
    '/* A picture of the dark theme (Appearance), whatever the theme. */',
    '.keep-dark {',
    '  color-scheme: dark;',
    ...block(dark, '  '),
    ...refBlock('  '),
    '}',
    '/* Text inside a scope is its ink, not the colour inherited from the page around it. In',
    '   the base layer, so a colour the element sets itself (a component, a text-* utility) wins. */',
    '@layer base {',
    '  .keep-light,',
    '  .keep-dark {',
    '    color: var(--ink);',
    '  }',
    '}',
    '/* Paper is white: a printed report or recovery-code sheet is in the light theme whatever the screen shows. */',
    '@media print {',
    "  :root[data-theme='dark'],",
    '  :root:not([data-theme]) {',
    '    color-scheme: light;',
    ...block(light, '    '),
    ...refBlock('    '),
    '  }',
    '}',
    '',
  ]
  return { tokens: lines.join('\n'), themes: themes.join('\n') }
}

export function readTokens(): Tokens {
  return JSON.parse(readFileSync(tokensJSON, 'utf8')) as Tokens
}

if (import.meta.url.startsWith('file:') && process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const out = build(readTokens())
  writeFileSync(tokensCSS, out.tokens)
  writeFileSync(themesCSS, out.themes)
  console.log(`wrote ${tokensCSS}\nwrote ${themesCSS}`)
}
